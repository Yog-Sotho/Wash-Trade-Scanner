"""
Render evaluation results as docs/benchmarks.md.
"""

from __future__ import annotations

from typing import Any

from config.settings import settings
from core.calibration import DetectorCalibration
from evaluation.inject import PATTERNS

PATTERN_SOURCES = {
    "aa_round_trip": "Chainalysis 2025, wash-trading heuristic 1",
    "aa_round_trip_slow": "heuristic 1 mechanism, legs 26-300 blocks apart",
    "funded_ring": "Chainalysis heuristic 2; Gan et al., ACM TOIT 2024",
    "unlinked_ring": "the same ring without observable funding links",
    "repeated_size_bot": "Kaiko on the NexFundAI market (2024)",
}


def _fmt(value: Any, pct: bool = False) -> str:
    if value is None:
        return "–"
    if pct:
        return f"{value * 100:.2f}%"
    if isinstance(value, float):
        return f"{value:.3f}"
    return str(value)


def _headline_row(label: str, d: dict[str, Any], documented: list[str]) -> str:
    o = d["overall"]
    c = d["clean_pools"]["all"]
    doc = [d["documented_wash"].get(n, {}) for n in documented]
    doc_cells = " | ".join(_fmt(x.get("flagged_share"), pct=True) for x in doc)
    return (
        f"| {label} | {_fmt(o['precision'])} | {_fmt(o['recall'])} | {_fmt(o['f1'])} "
        f"| {_fmt(o['pr_auc'])} | {_fmt(c['fpr'], pct=True)} "
        f"| {_fmt(c['fp_volume_share'], pct=True)} | {doc_cells} |"
    )


def render(
    results: dict[str, Any],
    before: dict[str, Any] | None = None,
    tuning: dict[str, Any] | None = None,
) -> str:
    detectors: dict[str, Any] = results["detectors"]
    fixtures: dict[str, Any] = results["fixtures"]
    clean = [n for n, m in fixtures.items() if m["kind"] == "clean"]
    documented = [n for n, m in fixtures.items() if m["kind"] == "documented_wash"]
    lines: list[str] = []
    add = lines.append

    add("# Detection Benchmarks")
    add("")
    add(
        "Generated by `wash-eval --write-docs` (`make eval`) from the harness in "
        "`evaluation/`. Every number is measured; the run is deterministic and makes "
        "no network calls, so re-running it reproduces this file exactly. CI re-runs "
        "it (`wash-eval --check`) and fails on a regression."
    )
    add("")

    # ------------------------------------------------------------ headline
    add("## Headline")
    add("")
    add(
        "The audit's decision (which trades it labels wash) before and after Phase 2, "
        f"on the same data. Labelled scenarios: {results['scenarios']} "
        f"({results['seeds']} seeds × {len(results['patterns'])} patterns × "
        f"{len(clean)} clean pools)."
    )
    add("")
    doc_headers = " | ".join(f"`{n}` trades flagged" for n in documented)
    add(
        "| Audit | Precision | Recall | F1 | PR-AUC | Clean-pool FPR | Clean FP volume | "
        + doc_headers
        + " |"
    )
    add("|---|---|---|---|---|---|---|" + "---|" * len(documented))
    if before is not None:
        add(
            _headline_row(
                f"Phase 1 (`{before.get('commit', 'main')}`)",
                before["detectors"]["phase1_audit"],
                documented,
            )
        )
    add(_headline_row("Phase 2 (calibrated composite)", detectors["composite"], documented))
    add("")
    if before is not None:
        self_trading = before["detectors"].get("self_trading")
        if self_trading:
            per_pool = ", ".join(
                f"`{n}` {_fmt(self_trading['clean_pools'][n]['fpr'], pct=True)}"
                for n in clean
                if n in self_trading["clean_pools"]
            )
            add(
                "Phase 1's `self_trading` detector alone flagged, of the honest trades in "
                f"each clean pool: {per_pool}. It compared the swap event's `sender` and "
                "`to`, which are the same contract whenever a bot or aggregator calls the "
                "pool directly. Phase 2 attributes each swap to the transaction's sender "
                "and replaces it with `round_trip`."
            )
            add("")

    # ------------------------------------------------------------ data
    add("## Data")
    add("")
    add("| Fixture | Kind | Pool | Blocks | Swaps | With tx sender | USD-valued |")
    add("|---|---|---|---|---|---|---|")
    for name, meta in fixtures.items():
        add(
            f"| `{name}` | {meta['kind']} | `{meta['pool_address']}` | "
            f"{meta['from_block']:,}–{meta['to_block']:,} | {meta['trades']:,} | "
            f"{meta['with_tx_from']:,} | {meta['priced']:,} |"
        )
    add("")
    add(
        "Fixtures are real swap histories recorded from Ethereum mainnet by the "
        "production ingestor (`python -m evaluation.record`): the same log decoding, "
        "transaction-sender lookup and USD valuation as an audit (ETH valued from "
        "Coinbase Exchange hourly candles, see `evaluation/record.py`). Clean fixtures "
        "are the most liquid USDC/USDT–WETH pools, which Chainalysis excludes from "
        "wash-trading analysis as unlikely to involve it. Every trade a detector flags "
        "there counts as a false positive, so clean-pool false-positive rates are "
        "upper bounds."
    )
    add("")
    add(
        f"Each labelled scenario is one clean fixture plus one injected campaign "
        f"({results['injected_trades']:,} injected wash trades against "
        f"{results['background_trades']:,} background trades in total; "
        "`evaluation/inject.py`). Detector rates used for scoring are measured on "
        "separate development seeds; the numbers reported here come from seeds the "
        "calibration never saw."
    )
    add("")
    add("| Pattern | Source |")
    add("|---|---|")
    for pattern in results["patterns"]:
        add(f"| `{pattern}` | {PATTERN_SOURCES.get(pattern, '')} |")
    add("")

    # ------------------------------------------------------------ detectors
    add("## Detectors")
    add("")
    add(
        "Each detector run on its own (`composite` is the audit's decision). "
        "Trade-level, pooled over all scenarios. Precision depends on how many wash "
        "trades are injected relative to the background, so the clean-pool "
        "false-positive rate is the more transferable number."
    )
    add("")
    add("| Detector | Precision | Recall | F1 | PR-AUC | Clean FPR | Clean FP volume |")
    add("|---|---|---|---|---|---|---|")
    for name, d in detectors.items():
        o = d["overall"]
        c = d["clean_pools"]["all"]
        add(
            f"| `{name}` | {_fmt(o['precision'])} | {_fmt(o['recall'])} | {_fmt(o['f1'])} "
            f"| {_fmt(o['pr_auc'])} | {_fmt(c['fpr'], pct=True)} "
            f"| {_fmt(c['fp_volume_share'], pct=True)} |"
        )
    add("")
    add("### Recall by pattern")
    add("")
    patterns = [p for p in PATTERNS if p in results["patterns"]]
    add("| Detector | " + " | ".join(f"`{p}`" for p in patterns) + " |")
    add("|---|" + "---|" * len(patterns))
    for name, d in detectors.items():
        cells = [_fmt(d["by_pattern"].get(p, {}).get("recall")) for p in patterns]
        add(f"| `{name}` | " + " | ".join(cells) + " |")
    add("")
    add("### False positives per clean pool")
    add("")
    add("Share of honest trades (and of their USD volume) flagged, no wash trading injected.")
    add("")
    add("| Detector | " + " | ".join(f"`{n}`" for n in clean) + " |")
    add("|---|" + "---|" * len(clean))
    for name, d in detectors.items():
        cells = [
            f"{_fmt(d['clean_pools'][n]['fpr'], pct=True)} "
            f"({_fmt(d['clean_pools'][n]['fp_volume_share'], pct=True)} vol)"
            for n in clean
        ]
        add(f"| `{name}` | " + " | ".join(cells) + " |")
    add("")

    flags = detectors["composite"].get("clean_flags", {})
    if any(flags.values()):
        add("### What the audit flags in the clean pools")
        add("")
        add(
            "Every trade the composite labels wash in the honest pools, by trader. Legs "
            "are `block:side $value` (side A is the trader's first direction). Some of "
            "these are plausibly real wash or MEV round trips, which is why clean-pool "
            "rates are upper bounds."
        )
        add("")
        add("| Pool | Trader | Trades | Volume | Legs |")
        add("|---|---|---|---|---|")
        for pool, traders in flags.items():
            for t in traders:
                legs = " ".join(
                    f"{leg['block']:,}:{leg['side']} ${leg['usd']:,.0f}" for leg in t["legs"][:8]
                )
                more = " …" if len(t["legs"]) > 8 else ""
                add(
                    f"| `{pool}` | `{t['trader']}` | {t['trades']} | "
                    f"${t['volume_usd']:,.0f} | {legs}{more} |"
                )
        add("")

    # ------------------------------------------------------------ calibration
    calibration = results.get("calibration")
    if calibration:
        prior = settings.WASH_PRIOR
        threshold = settings.SUSPICIOUS_ACTIVITY_THRESHOLD
        add("## Calibration")
        add("")
        add(
            "Rates shipped in `config/detector_calibration.json`, measured on the "
            "development seeds. A hit's score is P(wash | hit) by Bayes' rule with "
            f"prior WASH_PRIOR = {prior} and the 95% upper bound of the clean-pool "
            f"false-positive rate; a trade is labelled wash at ≥ {threshold} "
            "(SUSPICIOUS_ACTIVITY_THRESHOLD). A detector below that can raise a "
            "trade's score but cannot label it alone."
        )
        add("")
        add("| Detector | TPR | Clean FP | FPR (95% upper) | P(wash \\| hit) | Labels alone |")
        add("|---|---|---|---|---|---|")
        for name, c in calibration.items():
            posterior = DetectorCalibration(c["tpr"], c["fpr_upper"]).posterior(prior)
            add(
                f"| `{name}` | {_fmt(c['tpr'])} | {c['clean_false_positives']:,} / "
                f"{c['clean_trades']:,} | {_fmt(c['fpr_upper'], pct=True)} "
                f"| {_fmt(posterior)} | {'yes' if posterior >= threshold else 'no'} |"
            )
        add("")

    # ------------------------------------------------------------ ML
    ml = results.get("ml_isolation_forest")
    if ml and ml.get("folds"):
        add("## Isolation Forest (leave-one-pool-out)")
        add("")
        add(
            "The reference model (default features and contamination) is fitted on "
            "the other clean pools, its threshold set there to a "
            f"{settings.ML_TARGET_FPR:.0%} false-positive rate (ML_TARGET_FPR), and "
            "measured on the held-out pool's labelled scenarios. PR-AUC of a random "
            "ranking equals the prevalence."
        )
        add("")
        add("| Held-out pool | PR-AUC | Prevalence (random PR-AUC) | Recall | Clean FPR |")
        add("|---|---|---|---|---|")
        for name, fold in ml["folds"].items():
            add(
                f"| `{name}` | {_fmt(fold['pr_auc'])} | {_fmt(fold['prevalence'])} "
                f"| {_fmt(fold['tpr'])} | {_fmt(fold['fpr'], pct=True)} |"
            )
        add(
            f"| **mean** | {_fmt(ml['mean_pr_auc'])} ± {_fmt(ml['std_pr_auc'])} | | "
            f"{_fmt(ml['mean_tpr'])} | {_fmt(ml['mean_fpr'], pct=True)} |"
        )
        add("")
        add(
            f"`wash-train` measures every model it trains the same way, stores the "
            f"rates in the model file (audits score the model's hits with them), and "
            f"refuses to save a model whose PR-AUC is under {settings.ML_MIN_PR_AUC_LIFT}× "
            "that of a random ranking (ML_MIN_PR_AUC_LIFT)."
        )
        add("")

    # ------------------------------------------------------------ documented
    if documented:
        from evaluation.runner import DOCUMENTED_CASES

        add("## Documented wash-trading market")
        add("")
        for n in documented:
            meta = fixtures[n]
            add(f"`{n}`: {meta['description']}.")
            add("")
            if n in DOCUMENTED_CASES:
                add(DOCUMENTED_CASES[n])
                add("")
            add(
                "Without trade-level labels this reports how much of the market each "
                "detector flags."
            )
            add("")
            add("| Detector | Trades flagged | Volume flagged |")
            add("|---|---|---|")
            rows = list(detectors.items())
            if before is not None:
                rows.append(("phase1_audit (before)", before["detectors"]["phase1_audit"]))
            for name, d in rows:
                doc = d["documented_wash"].get(n, {})
                add(
                    f"| `{name}` | {_fmt(doc.get('flagged_share'), pct=True)} "
                    f"| {_fmt(doc.get('flagged_volume_share'), pct=True)} |"
                )
            add("")
            add(
                "Phase 1's share here came from its `self_trading` rule, which flags any "
                "swap a contract makes for itself -- 70-79% of the honest trades in the "
                "clean pools above -- not from detecting this market's wash trading. "
                "Phase 2's detectors label none of it: the documented mechanism is "
                "multi-wallet, and funding links are not in the recorded data. This is the "
                "largest open gap (see docs/project/roadmap_to_9.md)."
            )
            add("")

    # ------------------------------------------------------------ tuning
    if tuning:
        add("## Parameter selection")
        add("")
        add(
            "Chosen by `python -m evaluation.tune` on the development seeds: the "
            "highest-recall setting whose hits are decisive on their own "
            "(P(wash | hit) ≥ SUSPICIOUS_ACTIVITY_THRESHOLD at WASH_PRIOR); if none is, "
            "the highest-recall setting. Shipped defaults are in `config/settings.py`."
        )
        add("")
        add("| Detector | Chosen parameters | Dev recall | Clean FP | P(wash \\| hit) | Decisive |")
        add("|---|---|---|---|---|---|")
        for name, outcome in tuning.items():
            best = outcome["best"]
            params = ", ".join(f"{k}={v}" for k, v in best["params"].items())
            add(
                f"| `{name}` | {params} | {_fmt(best['tpr'])} | {best['clean_fp']:,} / "
                f"{best['clean_trades']:,} | {_fmt(best['posterior'])} "
                f"| {'yes' if outcome['decisive'] else 'no'} |"
            )
        add("")
    return "\n".join(lines) + "\n"
